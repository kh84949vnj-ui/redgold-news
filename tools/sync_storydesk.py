"""Copy prompter/js/board.js into the Story Desk page (site/index.html).

The Story Desk runs on claude.ai and can't load files from the prompter site,
so it carries its own copy of the board wording. This rewrites that copy
between the >>> / <<< markers. tests/test_storydesk.py fails if they differ.

  python tools/sync_storydesk.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START = "  // >>> board.js (generated by tools/sync_storydesk.py; edit prompter/js/board.js instead)\n"
END = "  // <<< board.js\n"


def inline_board() -> str:
    js = (ROOT / "prompter/js/board.js").read_text(encoding="utf-8")
    js = re.sub(r"^export ", "", js, flags=re.M)
    return "".join(("  " + line if line.strip() else line) for line in js.splitlines(keepends=True)).rstrip() + "\n"


def current_block(html: str) -> str:
    return html[html.index(START) + len(START): html.index(END)]


def main() -> None:
    page = ROOT / "site/index.html"
    html = page.read_text(encoding="utf-8")
    new = html[: html.index(START) + len(START)] + inline_board() + html[html.index(END):]
    page.write_text(new, encoding="utf-8")
    print("Story Desk board wording synced.")


if __name__ == "__main__":
    main()
